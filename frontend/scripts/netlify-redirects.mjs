/* =========================================================================
   DEPLOY-TIME ROUTING AND CONTENT SECURITY POLICY
   =========================================================================
   Netlify cannot interpolate environment variables into `netlify.toml`, so the
   two things that depend on WHICH backend this deploy talks to are generated
   here, at build time, into the publish directory:

     _redirects  — proxy /api/* to the certified backend, then the SPA fallback
     _headers    — the Content-Security-Policy, whose connect-src must name
                   that same backend origin

   IT FAILS THE BUILD WHEN NO BACKEND IS CONFIGURED. That is the point. A
   frontend published without an API still renders, still shows a sign-in form,
   and cannot authenticate anybody — it looks deployed and is not. Better to
   stop here, where the failure is one line in a build log, than to find out
   from a customer.

   This file exists in the frontend because it ships the frontend. It knows
   nothing about tax.
   ========================================================================= */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const DIST = resolve(process.cwd(), 'dist')

/** The backend origin this deploy talks to, e.g. https://api.onyxledger.ca */
const apiOrigin = (process.env.ONYX_API_ORIGIN ?? '').trim().replace(/\/+$/, '')

function fail(message) {
  console.error(`\n  netlify-redirects: ${message}\n`)
  process.exit(1)
}

if (!apiOrigin) {
  fail(
    'ONYX_API_ORIGIN is not set.\n' +
      '  Set it to the certified backend origin for this environment, e.g.\n' +
      '    ONYX_API_ORIGIN=https://api.staging.onyxledger.ca\n' +
      '  Refusing to publish a frontend with no API to talk to.',
  )
}

let origin
try {
  origin = new URL(apiOrigin)
} catch {
  fail(`ONYX_API_ORIGIN is not a valid URL: ${apiOrigin}`)
}

// http:// would send bearer tokens and tax data in clear text. localhost is
// exempt because a developer pointing a local build at a local backend is not
// a deploy, and the check should not force them to invent certificates.
const isLocal = origin.hostname === 'localhost' || origin.hostname === '127.0.0.1'
if (origin.protocol !== 'https:' && !isLocal) {
  fail(`ONYX_API_ORIGIN must be https:// (got ${origin.protocol}//). Refusing to publish.`)
}

/* ------------------------------------------------------------ redirects -- */

// The API proxy comes FIRST: a catch-all SPA rule above it would swallow every
// request and serve index.html to the API client.
const redirects = `# Generated by scripts/netlify-redirects.mjs — do not edit by hand.
# Backend for this deploy: ${origin.origin}

/api/*  ${origin.origin}/api/:splat  200

# Single-page app: every other path is a client route, not a file.
/*      /index.html                  200
`

/* ----------------------------------------------------------------- CSP --- */

/**
 * ONE definition of the policy.
 *
 * `script-src 'self'` with no 'unsafe-inline' and no 'unsafe-eval': the build
 * emits external module scripts only, and nothing evaluates strings.
 *
 * `style-src 'self'` — NO 'unsafe-inline'. Keeping it out is what the layout
 * utility classes are for; the frontend carries no inline style attributes, so
 * an injected <style> or style= cannot take effect either. This is the half of
 * CSP that is normally surrendered without argument, and surrendering it is
 * what makes CSS-based data exfiltration possible.
 *
 * `connect-src` names exactly this deploy's backend. A page that is somehow
 * induced to fetch cannot reach an attacker's collector.
 *
 * `frame-ancestors 'none'` is the modern clickjacking control; X-Frame-Options
 * in netlify.toml covers browsers that predate it.
 */
const csp = [
  "default-src 'none'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  `connect-src 'self' ${origin.origin}`,
  "form-action 'none'",
  "frame-ancestors 'none'",
  "base-uri 'none'",
  "object-src 'none'",
  "manifest-src 'self'",
  'upgrade-insecure-requests',
].join('; ')

const headers = `# Generated by scripts/netlify-redirects.mjs — do not edit by hand.
/*
  Content-Security-Policy: ${csp}
`

writeFileSync(resolve(DIST, '_redirects'), redirects, 'utf8')
writeFileSync(resolve(DIST, '_headers'), headers, 'utf8')

console.log(`netlify-redirects: API proxied to ${origin.origin}`)
console.log(`netlify-redirects: CSP written (style-src without 'unsafe-inline')`)
